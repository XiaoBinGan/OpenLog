  var current = FALLBACK;

  function pick(saved) {
    if (saved && DICT[saved]) return saved;
    var nav = root.navigator || {};
    var tag = (nav.languages && nav.languages[0]) || nav.language || '';
    return /^zh/i.test(tag) ? 'zh' : 'en';
  }

  function stored() {
    try { return root.localStorage.getItem(STORAGE_KEY); } catch (e) { return null; }
  }

  function guess() {
    return pick(stored());
  }

  function t(key) {
    var table = DICT[current] || DICT[FALLBACK] || {};
    if (table[key] != null) return table[key];
    var base = DICT[FALLBACK] || {};
    return base[key] != null ? base[key] : '';
  }

  function format(key, vars) {
    var out = t(key);
    for (var k in vars) {
      if (Object.prototype.hasOwnProperty.call(vars, k)) {
        out = out.split('{' + k + '}').join(vars[k]);
      }
    }
    return out;
  }

  function each(sel, fn) {
    var list = root.document.querySelectorAll(sel);
    for (var i = 0; i < list.length; i++) fn(list[i]);
  }

  /* 展开态下的 aria-label（收起 / 展开两种键） */
  function refreshAria() {
    if (!root.document) return;
    each('[data-i18n-aria]', function (el) {
      var alt = el.getAttribute('data-i18n-aria-alt');
      var open = el.getAttribute('aria-expanded') === 'true';
      el.setAttribute('aria-label', t(open && alt ? alt : el.getAttribute('data-i18n-aria')));
    });
  }

  function applyLang(lang) {
    var next = DICT[lang] ? lang : FALLBACK;
    current = next;
    var d = root.document;
    if (!d) return next;

    d.documentElement.setAttribute('lang', HTML_LANG[next] || next);

    each('[data-i18n]', function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    each('[data-i18n-html]', function (el) {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    each('[data-i18n-placeholder]', function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    each('[data-i18n-title]', function (el) {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    each('[data-i18n-content]', function (el) {
      el.setAttribute('content', t(el.getAttribute('data-i18n-content')));
    });
    refreshAria();

    /* 切换按钮高亮 */
    each('[data-lang]', function (btn) {
      var on = btn.getAttribute('data-lang') === next;
      if (on) btn.classList.add('is-active');
      else btn.classList.remove('is-active');
      btn.setAttribute('aria-pressed', on ? 'true' : 'false');
    });

    try { root.localStorage.setItem(STORAGE_KEY, next); } catch (e) {}

    if (d.dispatchEvent && root.CustomEvent) {
      d.dispatchEvent(new root.CustomEvent('openlog:lang', { detail: { lang: next } }));
    }
    return next;
  }

  var I18n = {
    dict: DICT,
    storageKey: STORAGE_KEY,
    get lang() { return current; },
    guess: guess,
    applyLang: applyLang,
    t: t,
    format: format,
    refreshAria: refreshAria,
    toggle: function () { return applyLang(current === 'zh' ? 'en' : 'zh'); }
  };

  root.OpenLogI18n = I18n;

  if (!root.document) return;

  /* 语言按钮：事件委托，点完立即切换，不刷新页面 */
  root.document.addEventListener('click', function (e) {
    var btn = e.target && e.target.closest ? e.target.closest('[data-lang]') : null;
    if (!btn) return;
    var lang = btn.getAttribute('data-lang');
    if (!DICT[lang] || lang === current) return;
    e.preventDefault();
    applyLang(lang);
  });

